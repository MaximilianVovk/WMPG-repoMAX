@dataclass(frozen=True)
class CameraConfig:
    name: str
    limiting_magnitude: float
    fps: float
    minimum_frames: float
    horizontal_fov_deg: float
    vertical_fov_deg: float
    pointing_mode: str = "horizon-anchored"
    lower_elevation_deg: float = 5.0
    boresight_zenith_deg: float | None = None
    vertical_optical_depth: float = 0.0
    airmass_floor_elevation_deg: float = 5.0
    fov_residence_mode: str = "minimum-dimension"
    transverse_speed_factor: float = 1.0

    def elevation_bounds_deg(self) -> tuple[float, float]:
        if self.pointing_mode == "horizon-anchored":
            lower = float(self.lower_elevation_deg)
            upper = lower + float(self.vertical_fov_deg)
        elif self.pointing_mode == "boresight":
            if self.boresight_zenith_deg is None:
                raise ValueError(
                    f"Camera {self.name!r} uses boresight mode but has no boresight_zenith_deg."
                )
            center_elevation = 90.0 - float(self.boresight_zenith_deg)
            lower = center_elevation - 0.5*float(self.vertical_fov_deg)
            upper = center_elevation + 0.5*float(self.vertical_fov_deg)
        else:
            raise ValueError(f"Unsupported pointing mode: {self.pointing_mode!r}")

        lower = max(0.0, lower)
        upper = min(90.0, upper)
        if upper <= lower:
            raise ValueError(
                f"Camera {self.name!r} has invalid elevation bounds {lower:.3f}–{upper:.3f} deg."
            )
        return lower, upper


