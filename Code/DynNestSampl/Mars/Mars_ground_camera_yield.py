def slant_range_to_shell_km(height_km: float, elevation_deg: np.ndarray | float) -> np.ndarray:
    elevation = np.deg2rad(np.asarray(elevation_deg, dtype=float))
    shell_radius = R_MARS_KM + float(height_km)
    term = (R_MARS_KM*np.sin(elevation))**2 + shell_radius**2 - R_MARS_KM**2
    term = np.maximum(term, 0.0)
    return -R_MARS_KM*np.sin(elevation) + np.sqrt(term)


def central_angle_to_shell_rad(height_km: float, elevation_deg: np.ndarray | float) -> np.ndarray:
    elevation = np.deg2rad(np.asarray(elevation_deg, dtype=float))
    slant = slant_range_to_shell_km(height_km, elevation_deg)
    vertical = R_MARS_KM + slant*np.sin(elevation)
    horizontal = slant*np.cos(elevation)
    return np.arctan2(horizontal, vertical)


def shell_wedge_strip_area_km2(
    height_km: float,
    elevation_low_deg: np.ndarray,
    elevation_high_deg: np.ndarray,
    horizontal_fov_deg: float,
) -> np.ndarray:
    delta_low = central_angle_to_shell_rad(height_km, elevation_low_deg)
    delta_high = central_angle_to_shell_rad(height_km, elevation_high_deg)
    azimuth_width = np.deg2rad(float(horizontal_fov_deg))
    shell_radius = R_MARS_KM + float(height_km)
    area = azimuth_width*shell_radius**2*(np.cos(delta_high) - np.cos(delta_low))
    return np.maximum(np.asarray(area, dtype=float), 0.0)


def range_to_vertical_column_km(height_km: np.ndarray, central_angle_rad: float) -> np.ndarray:
    shell_radius = R_MARS_KM + np.asarray(height_km, dtype=float)
    return np.sqrt(
        R_MARS_KM**2 + shell_radius**2
        - 2.0*R_MARS_KM*shell_radius*np.cos(float(central_angle_rad))
    )


def extinction_magnitude(camera: CameraConfig, elevation_deg: float) -> float:
    if camera.vertical_optical_depth <= 0.0:
        return 0.0
    floor = max(float(camera.airmass_floor_elevation_deg), 0.1)
    effective_elevation = max(float(elevation_deg), floor)
    airmass = 1.0/max(math.sin(math.radians(effective_elevation)), 1.0e-6)
    return 1.086*float(camera.vertical_optical_depth)*airmass


def duration_below_limit(time_s: np.ndarray, magnitude: np.ndarray, limit: float) -> float:
    time = np.asarray(time_s, dtype=float)
    mag = np.asarray(magnitude, dtype=float)
    n = min(len(time), len(mag))
    if n < 2:
        return 0.0
    time = time[:n]
    mag = mag[:n]
    good = np.isfinite(time) & np.isfinite(mag)
    time = time[good]
    mag = mag[good]
    if len(time) < 2:
        return 0.0

    detected = mag <= float(limit)
    duration = 0.0
    for index in range(len(time) - 1):
        t0, t1 = time[index], time[index + 1]
        if t1 <= t0:
            continue
        m0, m1 = mag[index], mag[index + 1]
        d0, d1 = detected[index], detected[index + 1]
        if d0 and d1:
            duration += t1 - t0
        elif d0 != d1 and np.isfinite(m1 - m0) and not np.isclose(m1, m0):
            fraction = np.clip((float(limit) - m0)/(m1 - m0), 0.0, 1.0)
            crossing = t0 + fraction*(t1 - t0)
            duration += (crossing - t0) if d0 else (t1 - crossing)
    return float(max(duration, 0.0))


def profile_camera_metric(
    profile: MeteorProfile,
    camera: CameraConfig,
    elevation_subdivisions: int,
) -> ProfileCameraMetric:
    lower, upper = camera.elevation_bounds_deg()
    edges = np.linspace(lower, upper, int(elevation_subdivisions) + 1)
    centers = 0.5*(edges[:-1] + edges[1:])
    strip_area = shell_wedge_strip_area_km2(
        profile.peak_height_km,
        edges[:-1],
        edges[1:],
        camera.horizontal_fov_deg,
    )
    geometric_area = float(np.sum(strip_area))

    detectable_area = 0.0
    weighted_duration = 0.0
    weighted_frames = 0.0

    for elevation, area in zip(centers, strip_area):
        if not np.isfinite(area) or area <= 0.0:
            continue
        delta_peak = float(central_angle_to_shell_rad(profile.peak_height_km, elevation))
        ranges = range_to_vertical_column_km(profile.height_km, delta_peak)
        with np.errstate(divide="ignore", invalid="ignore"):
            apparent_mag = (
                profile.abs_mag
                + 5.0*np.log10(np.maximum(ranges, 1.0e-9)/100.0)
                + extinction_magnitude(camera, float(elevation))
            )
        bright_duration = duration_below_limit(
            profile.time_s, apparent_mag, camera.limiting_magnitude
        )

        if camera.fov_residence_mode == "minimum-dimension":
            angular_width = math.radians(min(camera.horizontal_fov_deg, camera.vertical_fov_deg))
            representative_range = float(slant_range_to_shell_km(profile.peak_height_km, elevation))
            transverse_speed = max(
                profile.representative_speed_kms*float(camera.transverse_speed_factor),
                1.0e-9,
            )
            fov_residence = angular_width*representative_range/transverse_speed
            visible_duration = min(bright_duration, fov_residence)
        elif camera.fov_residence_mode == "none":
            visible_duration = bright_duration
        else:
            raise ValueError(
                f"Unsupported fov_residence_mode {camera.fov_residence_mode!r}."
            )

        expected_frames = visible_duration*float(camera.fps)
        if expected_frames >= float(camera.minimum_frames):
            detectable_area += float(area)
            weighted_duration += float(area)*visible_duration
            weighted_frames += float(area)*expected_frames

    if detectable_area > 0.0:
        mean_duration = weighted_duration/detectable_area
        mean_frames = weighted_frames/detectable_area
    else:
        mean_duration = 0.0
        mean_frames = 0.0

    return ProfileCameraMetric(
        meteor_name=profile.meteor_name,
        scenario=profile.scenario,
        scenario_weight=profile.scenario_weight,
        representative_speed_kms=profile.representative_speed_kms,
        peak_height_km=profile.peak_height_km,
        peak_abs_mag=profile.peak_abs_mag,
        geometric_fov_area_km2=geometric_area,
        detectable_effective_area_km2=detectable_area,
        area_weighted_visible_duration_s=mean_duration,
        area_weighted_frames=mean_frames,
        detectable_area_fraction=(detectable_area/geometric_area if geometric_area > 0.0 else 0.0),
    )


