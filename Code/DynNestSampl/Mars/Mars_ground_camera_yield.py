def height_edges_from_args(minimum: float, maximum: float, step: float) -> np.ndarray:
    if step <= 0.0 or maximum <= minimum:
        raise ValueError("Height maximum must exceed minimum and step must be positive.")
    edges = np.arange(minimum, maximum + step, step, dtype=float)
    if edges[-1] < maximum - 1.0e-9:
        edges = np.append(edges, maximum)
    else:
        edges[-1] = maximum
    return edges


def weighted_mean(values: np.ndarray, weights: np.ndarray, default: float = np.nan) -> float:
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)
    good = np.isfinite(values) & np.isfinite(weights) & (weights > 0.0)
    if not np.any(good):
        return float(default)
    return float(np.sum(values[good]*weights[good])/np.sum(weights[good]))


