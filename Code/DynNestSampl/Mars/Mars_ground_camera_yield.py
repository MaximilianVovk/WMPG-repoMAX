def mem_corrected_cache_paths(mem_directory: str | Path) -> dict[str, Path]:
    """Return the persistent corrected-MEM cache paths in the MEM input folder."""
    root = Path(mem_directory).resolve()
    return {
        "speed_flux_csv": root/MEM_CORRECTED_SPEED_FILENAME,
        "state_summary_csv": root/MEM_CORRECTED_STATE_FILENAME,
        "metadata_json": root/MEM_CORRECTED_METADATA_FILENAME,
    }


def _source_file_signature(paths: Iterable[str | Path]) -> list[dict[str, Any]]:
    """Return a stable source signature based on absolute path, size and mtime."""
    signature: list[dict[str, Any]] = []
    unique_paths = sorted({Path(path).resolve() for path in paths}, key=lambda item: str(item))
    for path in unique_paths:
        stat = path.stat()
        signature.append({
            "path": str(path),
            "size_bytes": int(stat.st_size),
            "mtime_ns": int(stat.st_mtime_ns),
        })
    return signature


def mem_transform_source_signature(
    mem_directory: str | Path,
    trajectory_file: str | Path | None,
) -> tuple[Path, list[dict[str, Any]]]:
    """Build the cache signature without parsing the large flux_N contents."""
    root = Path(mem_directory).resolve()
    trajectory_path = discover_trajectory_file(root, trajectory_file)
    pairs = discover_flux_pairs(root)

    source_paths: list[Path] = [trajectory_path]
    for _, high_path, low_path in pairs:
        source_paths.extend((high_path, low_path))

    # options.txt controls the angular output frame when --flux-output-axes=auto.
    source_paths.extend(path.resolve() for path in root.rglob("options.txt") if path.is_file())
    return trajectory_path, _source_file_signature(source_paths)


