def load_state_transform_csv(path: str | Path) -> list[dict[str, Any]]:
    """Read a previously saved MEM state-transform summary."""
    rows: list[dict[str, Any]] = []
    with Path(path).open("r", encoding="utf-8-sig", newline="") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            parsed: dict[str, Any] = {}
            for key, value in row.items():
                if value is None or str(value).strip() == "":
                    parsed[key] = np.nan
                    continue
                try:
                    numeric = float(value)
                    parsed[key] = int(numeric) if key == "state_index" else numeric
                except ValueError:
                    parsed[key] = value
            rows.append(parsed)
    return rows


def load_corrected_mem_cache(
    mem_directory: str | Path,
    metadata: dict[str, Any],
) -> DetailedFluxResult:
    """Rebuild DetailedFluxResult from corrected files saved in the MEM folder."""
    paths = mem_corrected_cache_paths(mem_directory)

    mars_speeds: list[float] = []
    mars_flux: list[float] = []
    raw_speeds: list[float] = []
    raw_flux: list[float] = []
    with paths["speed_flux_csv"].open("r", encoding="utf-8-sig", newline="") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            try:
                speed_value = str(row.get("mars_relative_speed_kms", "")).strip()
                flux_value = str(row.get("stationary_mars_zenith_flux_m2_yr", "")).strip()
                if speed_value and flux_value:
                    mars_speeds.append(float(speed_value))
                    mars_flux.append(float(flux_value))
            except ValueError:
                pass
            try:
                raw_speed_value = str(row.get("moving_sampler_speed_bin_kms", "")).strip()
                raw_flux_value = str(row.get("raw_mem_zenith_flux_m2_yr", "")).strip()
                if raw_speed_value and raw_flux_value:
                    raw_speeds.append(float(raw_speed_value))
                    raw_flux.append(float(raw_flux_value))
            except ValueError:
                pass

    if not mars_speeds or not mars_flux:
        raise ValueError(f"Corrected MEM cache is empty or invalid: {paths['speed_flux_csv']}")

    result_metadata = metadata.get("result", {})
    source_files = metadata.get("source_signature", [])
    flux_files = [
        item["path"] for item in source_files
        if Path(str(item.get("path", ""))).name.lower().startswith("flux_")
    ]

    return DetailedFluxResult(
        mars_speed_midpoints_kms=np.asarray(mars_speeds, dtype=float),
        transformed_speed_flux_m2_yr=np.asarray(mars_flux, dtype=float),
        spacecraft_speed_midpoints_kms=np.asarray(raw_speeds, dtype=float),
        spacecraft_surface_flux_m2_yr=np.asarray(raw_flux, dtype=float),
        state_rows=load_state_transform_csv(paths["state_summary_csv"]),
        flux_files=flux_files,
        trajectory_file=str(result_metadata.get("trajectory_file", "")),
        output_axes=str(result_metadata.get("output_axes", "body-fixed")),
        speed_label_shift_kms=float(result_metadata.get("speed_label_shift_kms", 0.0)),
        state_weighting=str(result_metadata.get("state_weighting", "time")),
        sampling_altitude_mean_km=float(result_metadata.get("sampling_altitude_mean_km", np.nan)),
        sampling_altitude_min_km=float(result_metadata.get("sampling_altitude_min_km", np.nan)),
        sampling_altitude_max_km=float(result_metadata.get("sampling_altitude_max_km", np.nan)),
        flux_frame_scaling=str(result_metadata.get("flux_frame_scaling", "number-density")),
        selected_surface=str(result_metadata.get("selected_surface", "+z zenith")),
    )


