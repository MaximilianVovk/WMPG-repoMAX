def _candidate_column(fieldnames: list[str], candidates: tuple[str, ...]) -> str | None:
    normalized = {name.strip().lower(): name for name in fieldnames}
    for candidate in candidates:
        if candidate.lower() in normalized:
            return normalized[candidate.lower()]
    return None


def load_mem_speed_flux(path: str | Path) -> tuple[np.ndarray, np.ndarray, dict[str, Any]]:
    path = Path(path)
    text = path.read_text(encoding="utf-8-sig", errors="replace")
    first_data_line = next((line for line in text.splitlines() if line.strip() and not line.lstrip().startswith("#")), "")

    speeds: list[float] = []
    fluxes: list[float] = []
    source_columns: dict[str, str] = {}

    if "," in first_data_line:
        with path.open("r", encoding="utf-8-sig", newline="") as fh:
            reader = csv.DictReader(fh)
            fields = list(reader.fieldnames or [])
            speed_col = _candidate_column(fields, (
                "mars_speed_kms", "speed_kms", "speed_bin_mid_kms",
                "mars_relative_speed_kms", "velocity_kms",
            ))
            flux_col = _candidate_column(fields, (
                "flux_m2_yr", "reference_flux_above_mem_mass_m2_yr",
                "stationary_mars_zenith_flux_m2_yr",
                "mars_stationary_flux_m2_yr", "reference_speed_flux_m2_yr",
                "flux_per_m2_per_year",
            ))
            if speed_col is None or flux_col is None:
                raise ValueError(
                    f"Could not identify speed and flux columns in {path}. Fields: {fields}"
                )
            source_columns = {"speed": speed_col, "flux": flux_col}
            for row in reader:
                try:
                    speed = float(row[speed_col])
                    flux = float(row[flux_col])
                except (TypeError, ValueError, KeyError):
                    continue
                if np.isfinite(speed) and speed > 0.0 and np.isfinite(flux) and flux >= 0.0:
                    speeds.append(speed)
                    fluxes.append(flux)
    else:
        for line in text.splitlines():
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            parts = re.split(r"[\s,;]+", line.strip())
            if len(parts) < 2:
                continue
            try:
                speed = float(parts[0])
                flux = float(parts[1])
            except ValueError:
                continue
            if np.isfinite(speed) and speed > 0.0 and np.isfinite(flux) and flux >= 0.0:
                speeds.append(speed)
                fluxes.append(flux)
        source_columns = {"speed": "column_1", "flux": "column_2"}

    if not speeds:
        raise ValueError(f"No valid speed-flux rows were read from {path}.")

    speed_arr = np.asarray(speeds, dtype=float)
    flux_arr = np.asarray(fluxes, dtype=float)

    # Some MEM-extension CSVs repeat the same reference flux for every mass bin.
    # Collapse duplicate speeds by the median, which preserves repeated identical
    # values while avoiding an accidental multiplication by the number of mass bins.
    unique_speeds = np.unique(speed_arr)
    collapsed_flux = np.asarray([
        np.nanmedian(flux_arr[np.isclose(speed_arr, speed, rtol=0.0, atol=1.0e-9)])
        for speed in unique_speeds
    ])
    order = np.argsort(unique_speeds)
    unique_speeds = unique_speeds[order]
    collapsed_flux = collapsed_flux[order]

    return unique_speeds, collapsed_flux, {
        "path": str(path.resolve()),
        "source_columns": source_columns,
        "input_row_count": len(speed_arr),
        "unique_speed_bin_count": len(unique_speeds),
        "total_reference_flux_m2_yr": float(np.sum(collapsed_flux)),
    }


