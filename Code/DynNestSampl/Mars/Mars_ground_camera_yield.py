#!/usr/bin/env python3
"""
Estimate the annual yield of a ground-based Martian meteor camera.

The calculation combines:
  1. A library of Martian meteor light curves produced by Mars_meteors.py.
  2. A Mars-relative MEM speed distribution evaluated near 100 km altitude.
  3. A ground-camera field of view whose lower elevation can be anchored near
     the horizon (5 deg by default) or set through a boresight zenith angle.

Each physical meteor can have several Mars trigger-model realizations (rho,
dynamic pressure, and erosion energy). They are retained as alternative
profiles, but their weights sum to one per physical meteor so they do not
multiply the population rate.

The estimator is intentionally a first-order, height-sliced trade study. MEM
sets the population abundance in each Mars-relative speed bin, while the meteor
library supplies conditional Martian detection properties at the 100-km speed.
Each meteor is assigned to the height bin containing its peak absolute brightness.
For every profile and camera, the code integrates the area of the atmospheric
shell inside the FOV for which the profile is bright for enough frames. MEM
flux is then distributed over peak-height bins using the observed/simulated
speed-height distribution of the profile library.

Required inputs
---------------
--marsmeteor-total
    all_meteors_data.marsmeteor_total generated by the companion patched
    Mars_meteors script. Legacy files are accepted, but exact time/velocity
    arrays are preferred.

--mem-directory
    MEM output folder containing input.txt and matching HiDensity/LoDensity
    flux_001.txt, flux_002.txt, ... products. The script merges the two density
    components, removes the fictitious moving sampler velocity for every
    angular-speed cell, and constructs the Mars-relative zenith flux near the
    sampling altitude (normally 100 km). The corrected MEM distribution is
    cached in this same folder and reused on later runs when the sources and
    transformation settings have not changed.

--mem-flux-file
    Optional fallback for an already transformed two-column speed-flux file.

Outputs
-------
* height_speed_grid.csv
* height_summary.csv (detectable heights only by default)
* height_summary_all.csv (diagnostic, including rejected heights)
* profile_diagnostics.csv
* summary.json / summary.txt
* annual_detections_by_height.png
* effective_area_by_height.png
* frames_by_height.png
* speed_height_rate.png
* speed_support_diagnostics.csv
* MEM_Mars_corrected_speed_flux.csv (saved in --mem-directory)
* MEM_Mars_corrected_state_transform_summary.csv (saved in --mem-directory)
* MEM_Mars_corrected_cache.json (saved in --mem-directory)

All camera plots use peak luminous height on the vertical axis. By default, height bins with no frame-qualified detection cells are omitted from the main height products.
Only NumPy and Matplotlib are required.
"""

