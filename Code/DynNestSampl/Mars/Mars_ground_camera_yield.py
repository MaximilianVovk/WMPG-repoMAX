def corrected_mem_cache_is_valid(
    mem_directory: str | Path,
    settings: dict[str, Any],
    source_signature: list[dict[str, Any]],
) -> tuple[bool, dict[str, Any] | None, str]:
    """Check cache files, transformation settings and source file signatures."""
    paths = mem_corrected_cache_paths(mem_directory)
    missing = [str(path) for path in paths.values() if not path.exists()]
    if missing:
        return False, None, "corrected cache files are missing"

    try:
        metadata = json.loads(paths["metadata_json"].read_text(encoding="utf-8"))
    except Exception as exc:
        return False, None, f"could not read cache metadata: {exc}"

    if int(metadata.get("format_version", -1)) != MEM_CORRECTED_CACHE_VERSION:
        return False, metadata, "cache format version changed"
    if metadata.get("settings") != settings:
        return False, metadata, "MEM transformation settings changed"
    if metadata.get("source_signature") != source_signature:
        return False, metadata, "input.txt, options.txt, or flux_N source files changed"
    return True, metadata, "cache is current"


def load_mem_speed_flux_from_directory(
    mem_directory: str | Path,
    trajectory_file: str | Path | None = None,
    output_axes: str = "auto",
    trajectory_axes: str = "equatorial",
    speed_label_mode: str = "auto",
    state_weighting: str = "time",
    mars_speed_bin_width_kms: float = 1.0,
    expected_sampling_altitude_km: float = 100.0,
    sampling_altitude_tolerance_km: float = 25.0,
    skip_sampling_altitude_check: bool = False,
    flux_frame_scaling: str = "number-density",
    recompute_mem_cache: bool = False,
) -> tuple[np.ndarray, np.ndarray, dict[str, Any], DetailedFluxResult]:
    """
    Read all HiDensity/LoDensity flux_N pairs and remove sampler motion.

    The returned speed axis is Mars-relative at the MEM sampling positions,
    normally about 100 km altitude. The real camera/lander geometry is not used
    in this velocity transformation.
    """
    root = Path(mem_directory).resolve()
    trajectory_path, source_signature = mem_transform_source_signature(
        root, trajectory_file
    )
    cache_settings = mem_transform_cache_settings(
        trajectory_path=trajectory_path,
        output_axes=output_axes,
        trajectory_axes=trajectory_axes,
        speed_label_mode=speed_label_mode,
        state_weighting=state_weighting,
        mars_speed_bin_width_kms=mars_speed_bin_width_kms,
        expected_sampling_altitude_km=expected_sampling_altitude_km,
        sampling_altitude_tolerance_km=sampling_altitude_tolerance_km,
        skip_sampling_altitude_check=skip_sampling_altitude_check,
        flux_frame_scaling=flux_frame_scaling,
    )

    cache_used = False
    cache_reason = "forced recomputation"
    metadata: dict[str, Any] | None = None
    if not recompute_mem_cache:
        cache_valid, metadata, cache_reason = corrected_mem_cache_is_valid(
            root,
            settings=cache_settings,
            source_signature=source_signature,
        )
        if cache_valid and metadata is not None:
            result = load_corrected_mem_cache(root, metadata)
            cache_used = True
            print(
                f"Loaded corrected Mars-frame MEM distribution from "
                f"{mem_corrected_cache_paths(root)['speed_flux_csv']}"
            )
        else:
            print(f"Corrected MEM cache not reused: {cache_reason}.")

    if not cache_used:
        result = transform_flux_files_to_mars_frame(
            mem_directory=root,
            trajectory_file=trajectory_path,
            output_axes=output_axes,
            trajectory_axes=trajectory_axes,
            speed_label_mode=speed_label_mode,
            state_weighting_mode=state_weighting,
            flux_mode="zenith",
            selected_direction="+z zenith",
            mars_speed_bin_width_kms=mars_speed_bin_width_kms,
            mars_radius_km=R_MARS_KM,
            expected_sampling_altitude_km=expected_sampling_altitude_km,
            sampling_altitude_tolerance_km=sampling_altitude_tolerance_km,
            skip_sampling_altitude_check=skip_sampling_altitude_check,
            flux_frame_scaling=flux_frame_scaling,
        )
        cache_outputs = save_corrected_mem_cache(
            root,
            result=result,
            settings=cache_settings,
            source_signature=source_signature,
        )
        print(f"Saved corrected MEM cache in: {root}")
    else:
        cache_outputs = {
            key: str(path)
            for key, path in mem_corrected_cache_paths(root).items()
        }

    speeds = np.asarray(result.mars_speed_midpoints_kms, dtype=float)
    flux = np.asarray(result.transformed_speed_flux_m2_yr, dtype=float)
    valid = np.isfinite(speeds) & (speeds > 0.0) & np.isfinite(flux) & (flux >= 0.0)
    speeds = speeds[valid]
    flux = flux[valid]
    if not np.any(flux > 0.0):
        raise ValueError("The transformed MEM zenith distribution contains no positive flux.")

    # Drop empty leading/trailing bins but retain zero bins between populated bins.
    positive = np.flatnonzero(flux > 0.0)
    first, last = int(positive[0]), int(positive[-1])
    speeds = speeds[first:last + 1]
    flux = flux[first:last + 1]

    diagnostics = {
        "source": "MEM detailed flux_N directory",
        "mem_directory": str(Path(mem_directory).resolve()),
        "trajectory_file": result.trajectory_file,
        "flux_file_count": len(result.flux_files),
        "state_count": len(result.state_rows),
        "high_low_pairs": len(result.state_rows),
        "output_axes": result.output_axes,
        "state_weighting": result.state_weighting,
        "speed_label_shift_kms": result.speed_label_shift_kms,
        "sampling_altitude_mean_km": result.sampling_altitude_mean_km,
        "sampling_altitude_min_km": result.sampling_altitude_min_km,
        "sampling_altitude_max_km": result.sampling_altitude_max_km,
        "flux_frame_scaling": result.flux_frame_scaling,
        "selected_surface": result.selected_surface,
        "unique_speed_bin_count": len(speeds),
        "total_reference_flux_m2_yr": float(np.sum(flux)),
        "raw_moving_sampler_zenith_flux_m2_yr": float(
            np.sum(result.spacecraft_surface_flux_m2_yr)
        ),
        "interpretation": (
            "HiDensity and LoDensity are added for every state. Each angular-speed "
            "cell is transformed from the moving fictitious sampler frame to the "
            "Mars-relative frame at the same sampling position, then projected onto "
            "the local +z zenith plane and averaged over states."
        ),
        "corrected_cache_used": bool(cache_used),
        "corrected_cache_status": cache_reason,
        "corrected_cache_files": cache_outputs,
    }
    return speeds, flux, diagnostics, result


