def _finite_scalar(value: Any, default: float = np.nan) -> float:
    try:
        out = float(value)
    except (TypeError, ValueError):
        return float(default)
    return out if np.isfinite(out) else float(default)


def _const_value(const: Any, name: str, default: float = np.nan) -> float:
    if const is None:
        return float(default)
    if isinstance(const, dict):
        return _finite_scalar(const.get(name), default)
    return _finite_scalar(getattr(const, name, default), default)


def _prepare_profile(
    meteor_name: str,
    scenario: str,
    scenario_weight: float,
    abs_mag: Iterable[float],
    height_km: Iterable[float],
    length_km: Iterable[float] | None,
    time_s: Iterable[float] | None,
    speed_kms: Iterable[float] | None,
    const: Any,
) -> MeteorProfile | None:
    mag = np.asarray(abs_mag, dtype=float).reshape(-1)
    height = np.asarray(height_km, dtype=float).reshape(-1)
    n = min(len(mag), len(height))
    if n < 2:
        return None
    mag = mag[:n]
    height = height[:n]

    if length_km is None:
        length = np.arange(n, dtype=float)
    else:
        length = np.asarray(length_km, dtype=float).reshape(-1)[:n]
        if len(length) < n:
            length = np.pad(length, (0, n-len(length)), constant_values=np.nan)

    if speed_kms is not None:
        speed = np.asarray(speed_kms, dtype=float).reshape(-1)[:n]
        if len(speed) < n:
            speed = np.pad(speed, (0, n-len(speed)), constant_values=np.nan)
    else:
        speed = np.full(n, _const_value(const, "v_init")/1000.0, dtype=float)

    if time_s is not None:
        time = np.asarray(time_s, dtype=float).reshape(-1)[:n]
        if len(time) < n:
            time = np.pad(time, (0, n-len(time)), constant_values=np.nan)
    else:
        dt = _const_value(const, "dt")
        if np.isfinite(dt) and dt > 0.0:
            time = np.arange(n, dtype=float)*dt
        else:
            representative_speed = np.nanmedian(speed)
            if not np.isfinite(representative_speed) or representative_speed <= 0.0:
                representative_speed = _const_value(const, "v_init")/1000.0
            length0 = length - length[np.flatnonzero(np.isfinite(length))[0]] if np.any(np.isfinite(length)) else np.arange(n)
            time = length0/max(representative_speed, 1.0e-9)

    good = np.isfinite(mag) & np.isfinite(height) & np.isfinite(time)
    if np.count_nonzero(good) < 2:
        return None
    mag = mag[good]
    height = height[good]
    time = time[good]
    length = length[good]
    speed = speed[good]

    order = np.argsort(time)
    time = time[order]
    mag = mag[order]
    height = height[order]
    length = length[order]
    speed = speed[order]

    unique_time, unique_indices = np.unique(time, return_index=True)
    time = unique_time
    mag = mag[unique_indices]
    height = height[unique_indices]
    length = length[unique_indices]
    speed = speed[unique_indices]
    if len(time) < 2:
        return None

    # Ensure the profile starts at t=0 for stable duration calculations.
    time = time - time[0]

    finite_speed = speed[np.isfinite(speed) & (speed > 0.0)]
    representative_speed = (
        float(np.nanmedian(finite_speed))
        if finite_speed.size
        else _const_value(const, "v_init")/1000.0
    )
    if not np.isfinite(representative_speed) or representative_speed <= 0.0:
        return None

    # Fill missing speed samples with the profile representative speed.
    speed = np.where(np.isfinite(speed) & (speed > 0.0), speed, representative_speed)

    peak_index = int(np.nanargmin(mag))
    initial_mass = _const_value(const, "m_init")

    return MeteorProfile(
        meteor_name=meteor_name,
        scenario=scenario,
        scenario_weight=float(scenario_weight),
        time_s=time,
        height_km=height,
        abs_mag=mag,
        length_km=length,
        speed_kms=speed,
        initial_mass_kg=initial_mass,
        representative_speed_kms=representative_speed,
        peak_height_km=float(height[peak_index]),
        peak_abs_mag=float(mag[peak_index]),
    )


def load_mars_profiles(
    path: str | Path,
    scenarios: tuple[str, ...],
    include_single_body: bool = False,
) -> tuple[list[MeteorProfile], dict[str, Any]]:
    with Path(path).open("rb") as fh:
        payload = pickle.load(fh)

    selected = list(scenarios)
    if include_single_body and "single_body" not in selected:
        selected.append("single_body")

    profiles: list[MeteorProfile] = []
    used_exact_profiles = False
    ground_dict = payload.get("file_ground_camera_dict", {}) if isinstance(payload, dict) else {}

    if isinstance(ground_dict, dict) and ground_dict:
        used_exact_profiles = True
        for meteor_name, scenario_map in ground_dict.items():
            if not isinstance(scenario_map, dict):
                continue
            available = [name for name in selected if name in scenario_map]
            if not available:
                continue
            scenario_weight = 1.0/len(available)
            for scenario in available:
                record = scenario_map[scenario]
                if not isinstance(record, dict):
                    continue
                profile = _prepare_profile(
                    meteor_name=meteor_name,
                    scenario=scenario,
                    scenario_weight=scenario_weight,
                    abs_mag=record.get("abs_magnitude", []),
                    height_km=record.get("height_km", []),
                    length_km=record.get("length_km"),
                    time_s=record.get("time_s"),
                    speed_kms=record.get("speed_kms"),
                    const=record.get("const", record),
                )
                if profile is not None:
                    profiles.append(profile)
    else:
        bright_dict = payload.get("file_bright_dict", {}) if isinstance(payload, dict) else {}
        if not isinstance(bright_dict, dict) or not bright_dict:
            raise ValueError(
                "The Mars meteor file contains neither file_ground_camera_dict nor file_bright_dict."
            )

        # Legacy file_bright_dict tuple layout from Mars_meteors.py.
        scenario_indices = {
            "single_body": (3, 4, 5, 16),
            "rho": (6, 7, 8, 17),
            "dyn_pressure": (9, 10, 11, 18),
            "energy": (12, 13, 14, 19),
        }
        for meteor_name, values in bright_dict.items():
            if not isinstance(values, (tuple, list)) or len(values) < 20:
                continue
            available = [name for name in selected if name in scenario_indices]
            if not available:
                continue
            scenario_weight = 1.0/len(available)
            for scenario in available:
                mag_i, height_i, length_i, const_i = scenario_indices[scenario]
                profile = _prepare_profile(
                    meteor_name=meteor_name,
                    scenario=scenario,
                    scenario_weight=scenario_weight,
                    abs_mag=values[mag_i],
                    height_km=values[height_i],
                    length_km=values[length_i],
                    time_s=None,
                    speed_kms=None,
                    const=values[const_i],
                )
                if profile is not None:
                    profiles.append(profile)

    if not profiles:
        raise ValueError("No usable Martian light-curve profiles were loaded.")

    unique_meteors = sorted({profile.meteor_name for profile in profiles})
    diagnostics = {
        "profile_count": len(profiles),
        "physical_meteor_count": len(unique_meteors),
        "used_exact_time_velocity_profiles": used_exact_profiles,
        "selected_scenarios": selected,
    }
    return profiles, diagnostics


