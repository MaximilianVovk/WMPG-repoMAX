def load_camera_config_json(path: str | Path) -> list[CameraConfig]:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    entries = data.get("cameras", data) if isinstance(data, dict) else data
    if not isinstance(entries, list):
        raise ValueError("Camera JSON must contain a list or a {'cameras': [...]} mapping.")
    return [CameraConfig(**entry) for entry in entries]


